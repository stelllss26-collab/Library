"""
Библиотека забытых миров (The Library of Lost Worlds)
-----------------------------------------------------
Небольшой Flask-сервер, который отдаёт одну страницу — templates/index.html.
Вся интерактивность (каталог, поиск, фильтры, избранное, оракул, генератор
случайной книги) живёт на клиенте в static/js/app.js.

Запуск:
    python app.py
Затем откройте в браузере: http://127.0.0.1:5000/
"""

from flask import Flask, render_template

# создаём приложение; template_folder и static_folder Flask ищет сам,
# поэтому дополнительная настройка не нужна — структура папок стандартная
app = Flask(__name__)


@app.route("/")
def index():
    """Главная (и единственная) страница сайта."""
    return render_template("index.html")


if __name__ == "__main__":
    # debug=True удобен при локальной разработке: страница перезагружается
    # сама при изменении файлов. Для публичного размещения debug нужно выключить.
    app.run(host="127.0.0.1", port=5000, debug=True)
